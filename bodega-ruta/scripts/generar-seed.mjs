// Deterministic pseudo-random so the seed is stable between runs.
let s = 7;
const rnd = () => ((s = (s * 1103515245 + 12345) % 2147483648) / 2147483648);
const trayChoices = [1, 1.5, 2, 2.5, 3, 3.5, 4, 5];
const words = { 1: "1 bandeja", 1.5: "1 bandeja y media", 2: "2 bandejas", 2.5: "2 bandejas y media",
  3: "3 bandejas", 3.5: "3 bandejas y media", 4: "4 bandejas", 5: "5 bandejas" };

const pedidos = [];
for (let n = 0; n < 25; n++) {
  const cliente = clientes[n % clientes.length];
  const k = 1 + Math.floor(rnd() * 3);
  const items = [];
  const usados = new Set();
  while (items.length < k) {
    const pi = Math.floor(rnd() * productos.length);
    if (usados.has(pi)) continue;
    usados.add(pi);
    const bandejas = trayChoices[Math.floor(rnd() * trayChoices.length)];
    const [nom, varr, upb] = productos[pi];
    items.push({ nom, varr, unidades: Math.round(bandejas * upb), texto: `${words[bandejas]} de ${nom.toLowerCase()} ${varr.toLowerCase()}` });
  }
  pedidos.push({ cliente: cliente[0], items });
}

let sql = "-- GENERATED by scripts/generar-seed.mjs. Fictional data; prices/trays are PROVISIONAL.\n";
sql += "insert into productos (nombre, variante, unidades_por_bandeja, precio_unidad) values\n";
sql += productos.map((p) => `  (${q(p[0])}, ${q(p[1])}, ${p[2]}, ${p[3]})`).join(",\n") + "\non conflict do nothing;\n\n";
sql += "insert into clientes (nombre, direccion, telefono, lat, lng) values\n";
sql += clientes.map((c) => `  (${q(c[0])}, ${q(c[1])}, ${q(c[2])}, ${c[3]}, ${c[4]})`).join(",\n") + ";\n\n";
sql += "do $$ declare pid uuid; begin\n";
for (const p of pedidos) {
  sql += `  insert into pedidos (cliente_id) select id from clientes where nombre = ${q(p.cliente)} returning id into pid;\n`;
  for (const i of p.items) {
    sql += `  insert into pedido_items (pedido_id, producto_id, cantidad_pedida_unidades, texto_original) select pid, id, ${i.unidades}, ${q(i.texto)} from productos where nombre = ${q(i.nom)} and variante = ${q(i.varr)};\n`;
  }
}
sql += "end $$;\n";
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
